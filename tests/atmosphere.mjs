import assert from 'node:assert/strict';
import { World, W, TILE } from '../src/core/simulation.js';
import { forestShade } from '../src/render/atmosphere.js';
const w = new World('canopy-test'),
  z = w.cities[0];
Object.assign(w.player, { x: (z.x + 0.5) * TILE, y: (z.y + 0.5) * TILE });
let i = z.y * W + z.x;
w.tiles[i] = 0;
w.depth[i] = 18;
assert.equal(forestShade(w), 0, 'Even dense greenery in town does not darken the screen');
const p = { x: 20.5 * TILE, y: 20.5 * TILE };
i = 20 * W + 20;
w.tiles[i] = 0;
w.depth[i] = 10;
assert.equal(forestShade(w, p), 0, 'Forest edges and shallow woods are not darkened');
w.depth[i] = 12;
assert.ok(forestShade(w, p) > 0);
w.depth[i] = 18;
assert.equal(forestShade(w, p), 0.18);
assert.ok(w.terrain(p).speed < 0.7);
w.tiles[i] = 1;
assert.equal(forestShade(w, p), 0, 'Roads have no canopy effect');
w.tiles[i] = 8;
assert.equal(forestShade(w, p), 0, 'Meadows are not forests');
console.log('✓ Darkening only in deep slow forest, never on town grass, meadows or roads');
